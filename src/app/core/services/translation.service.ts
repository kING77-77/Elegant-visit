  constructor() {
    this.loadLanguage();
  }

  setLanguage(lang: Language): void {
    this.currentLang.set(lang);
    localStorage.setItem('selected_lang', lang);
  }

  translate(key: string): string {
    const lang = this.currentLang();
    const translations = this.dictionary[lang];
    if (translations && key in translations) {
      return translations[key];
    }

    // If it's a database seeded value (doesn't contain a dot '.'),
    // we should return the key itself (which is the seeded Russian text)
    // rather than falling back to Armenian.
    if (!key.includes('.')) {
      return key;
    }

    // Fallback to am for UI keys, then to key itself
    const amTranslations = this.dictionary['am'];
    if (amTranslations && key in amTranslations) {
      return amTranslations[key];
    }

    return key;
  }

  private loadLanguage(): void {
    const saved = localStorage.getItem('selected_lang');
    if (saved === 'am' || saved === 'ru' || saved === 'en' || saved === 'ka') {
      this.currentLang.set(saved);
    } else {
      this.currentLang.set('am'); // Default is Armenian
    }
  }
